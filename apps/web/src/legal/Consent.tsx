type Salon = { name: string; address: string | null; legalName: string | null; inn: string | null };

/**
 * Согласие клиента салона при онлайн-записи. Оператор — салон, Исполнитель обрабатывает по его поручению.
 * Страница: /b/:slug/consent
 */
export function ClientConsent() {
  const { slug = '' } = useParams();
  const [salon, setSalon] = useState<Salon | null>(null);
  useEffect(() => { api<Salon>(`/public/${slug}`).then(setSalon).catch(() => setSalon(null)); }, [slug]);

  const operator = salon
    ? `${salon.legalName || salon.name}${salon.inn ? `, ИНН ${salon.inn}` : ''}${salon.address ? `, адрес: ${salon.address}` : ''}`
    : 'салон, в который я записываюсь';

  return (
    <Doc title="Согласие на обработку персональных данных" subtitle={salon ? `для онлайн-записи в «${salon.name}»` : 'для онлайн-записи'}>
      <p>
        Записываясь онлайн, я свободно, своей волей и в своём интересе даю согласие {operator} (далее — «Салон») на обработку моих
        персональных данных на следующих условиях.
      </p>
      <h2>1. Перечень данных</h2>
      <p>
        Имя, номер телефона, адрес электронной почты (если укажу), комментарий к записи, сведения о моих записях и визитах (дата,
        время, услуги, мастер, стоимость), а если я подключу напоминания в мессенджере — мой идентификатор в Telegram, MAX или ВКонтакте.
      </p>
      <h2>2. Цели</h2>
      <p>
        Запись на услуги Салона; напоминания о визите на email или в выбранном мной мессенджере (Telegram, MAX, ВКонтакте); подтверждение, перенос и отмена записи; ведение истории
        моих визитов; связь со мной по вопросам записи; лист ожидания — сообщение, когда освободится время. Рекламные сообщения
        по этому согласию не отправляются. Поздравления и специальные предложения Салон присылает, только если я отдельно отметил(а)
        галочку «Хочу получать от салона поздравления и специальные предложения» (ст. 18 Федерального закона «О рекламе»);
        отписаться можно по ссылке в любом таком сообщении.
      </p>
      <h2>3. Действия и способы</h2>
      <p>
        Сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, передача (предоставление, доступ),
        обезличивание, блокирование, удаление, уничтожение. Обработка смешанная, с использованием средств автоматизации.
      </p>
      <h2>4. Кто ещё обрабатывает данные</h2>
      <p>
        По поручению Салона мои данные обрабатывает {O.fullName}, ИНН {O.inn} — владелец сервиса онлайн-записи «{O.service}».
        Данные хранятся на серверах в Российской Федерации. Для отправки писем привлекается {O.mailProvider}; если я сам подключу напоминания в
        мессенджере, сведения о записи передаются через {O.ruMessengers} (серверы в РФ). Если я сам подключу
        Telegram-бота, я согласен, что моё имя и сведения о записи будут переданы в мессенджер Telegram, серверы которого находятся за
        пределами РФ.
      </p>
      <h2>5. Срок и отзыв</h2>
      <p>
        Согласие действует 3 года с даты моего последнего визита или до его отзыва. Отозвать согласие можно, обратившись в Салон
        {salon?.address ? ` (${salon.address})` : ''} или направив письмо на {O.email} (обращение будет передано Салону).
      </p>
      <p className="text-sm text-ink-muted">
        Подробнее: <Link className="text-brand-600 underline" to="/privacy">Политика обработки персональных данных</Link>
      </p>
    </Doc>
  );
}
